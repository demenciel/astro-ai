#!/usr/bin/env node
// One-command, idempotent project setup. Safe to re-run at any time.
//
//   npm run setup                         # run every step that has the keys it needs
//   npm run setup -- --only=cloudflare,deploy
//
// Inputs come from .env.setup (gitignored) or environment variables. See
// .env.setup.example. Steps without their keys are skipped, never failed.
// Steps: project, local, cloudflare, stripe, deploy, github
import { readFileSync, unlinkSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import {
  PLACEHOLDER_DB_ID,
  SETUP_FILE,
  WORKER_SECRETS,
  exists,
  gitRepoSlug,
  has,
  loadSetupEnv,
  p,
  randomSecret,
  read,
  setEnvValue,
  sh,
  slugify,
  write,
  wranglerConfig,
} from './lib.mjs';

const ALL_STEPS = ['project', 'local', 'cloudflare', 'stripe', 'deploy', 'github'];
const only = process.argv
  .find((a) => a.startsWith('--only='))
  ?.slice(7)
  .split(',');
const steps = only ?? ALL_STEPS;

// Stripe events forwarded to /api/stripe/webhook (handled in src/pages/api/stripe/webhook.ts).
const WEBHOOK_EVENTS = [
  'checkout.session.completed',
  'checkout.session.async_payment_succeeded',
  'customer.subscription.updated',
  'customer.subscription.deleted',
  'invoice.payment_failed',
];

let env = loadSetupEnv();
const results = [];
const ok = (step, msg) => (results.push(['✔', step, msg]), console.log(`✔ ${step}: ${msg}`));
const skip = (step, msg) => (results.push(['…', step, msg]), console.log(`… ${step}: skipped (${msg})`));
const fail = (step, msg) => (results.push(['✖', step, msg]), console.log(`✖ ${step}: ${msg}`));

/** Persist a value to .env.setup so later runs (and deploys) reuse it. */
function remember(key, value) {
  if (!exists(SETUP_FILE)) write(SETUP_FILE, read('.env.setup.example') ?? '');
  setEnvValue(SETUP_FILE, key, value);
  env = { ...env, [key]: value };
}

function editWrangler(fn) {
  write('wrangler.jsonc', fn(read('wrangler.jsonc')));
}

// ---------------------------------------------------------------- project
function stepProject() {
  if (!env.PROJECT_NAME) return skip('project', 'pass PROJECT_NAME=<name> npm run setup');
  remember('PROJECT_NAME', env.PROJECT_NAME);
  const slug = slugify(env.PROJECT_NAME);
  const cfg = wranglerConfig();
  const oldQueue = cfg.queues?.producers?.[0]?.queue;
  editWrangler((t) =>
    t
      .replace(/^(\s*"name":\s*")[^"]*(")/m, `$1${slug}$2`)
      .replace(/("database_name":\s*")[^"]*(")/, `$1${slug}-db$2`)
      .replaceAll(`"queue": "${oldQueue}"`, `"queue": "${slug}-jobs"`)
  );
  const pkg = JSON.parse(read('package.json'));
  pkg.name = slug;
  write('package.json', JSON.stringify(pkg, null, 2) + '\n');
  ok('project', `named "${slug}" (worker, ${slug}-db, ${slug}-jobs)`);
}

// ---------------------------------------------------------------- local
function stepLocal() {
  if (!env.ADMIN_PASSWORD) remember('ADMIN_PASSWORD', randomSecret(12));
  if (!env.SESSION_SECRET) remember('SESSION_SECRET', randomSecret(32));
  const lines = ['# Generated by `npm run setup` from .env.setup. Local dev only.'];
  for (const k of WORKER_SECRETS) lines.push(`${k}=${env[k] ?? ''}`);
  write('.dev.vars', lines.join('\n') + '\n');
  const r = spawnSync('npx', ['wrangler', 'd1', 'migrations', 'apply', 'DB', '--local'], {
    cwd: p(''),
    stdio: 'ignore',
  });
  if (r.status !== 0) return fail('local', 'wrote .dev.vars but local migrations failed: run `npm run db:migrate`');
  ok('local', '.dev.vars written, local D1 migrated (admin password is ADMIN_PASSWORD in .env.setup)');
}

// ---------------------------------------------------------------- cloudflare
async function cf(path, init = {}) {
  const res = await fetch(`https://api.cloudflare.com/client/v4${path}`, {
    ...init,
    headers: { authorization: `Bearer ${env.CLOUDFLARE_API_TOKEN}`, 'content-type': 'application/json' },
  });
  const data = await res.json().catch(() => ({}));
  if (!data.success) {
    const err = new Error(data.errors?.map((e) => `${e.code}: ${e.message}`).join('; ') || `HTTP ${res.status}`);
    err.status = res.status;
    throw err;
  }
  return data.result;
}

async function stepCloudflare() {
  if (!env.CLOUDFLARE_API_TOKEN) return skip('cloudflare', 'set CLOUDFLARE_API_TOKEN');
  try {
    if (!env.CLOUDFLARE_ACCOUNT_ID) {
      const accounts = await cf('/accounts');
      if (accounts.length !== 1) {
        return fail(
          'cloudflare',
          `token sees ${accounts.length} accounts; set CLOUDFLARE_ACCOUNT_ID to one of: ${accounts.map((a) => `${a.id} (${a.name})`).join(', ')}`
        );
      }
      remember('CLOUDFLARE_ACCOUNT_ID', accounts[0].id);
    }
    const acc = `/accounts/${env.CLOUDFLARE_ACCOUNT_ID}`;
    const cfg = wranglerConfig();

    // D1
    const d1 = cfg.d1_databases[0];
    let dbId = d1.database_id !== PLACEHOLDER_DB_ID ? d1.database_id : null;
    if (!dbId) {
      const found = (await cf(`${acc}/d1/database?name=${encodeURIComponent(d1.database_name)}`)).find(
        (d) => d.name === d1.database_name
      );
      dbId =
        found?.uuid ??
        (await cf(`${acc}/d1/database`, { method: 'POST', body: JSON.stringify({ name: d1.database_name }) })).uuid;
      editWrangler((t) => t.replace(/("database_id":\s*")[^"]*(")/, `$1${dbId}$2`));
    }

    // Queue
    const queueName = cfg.queues.producers[0].queue;
    const queues = await cf(`${acc}/queues`);
    if (!queues.some((q) => q.queue_name === queueName)) {
      await cf(`${acc}/queues`, { method: 'POST', body: JSON.stringify({ queue_name: queueName }) });
    }

    // Public URL: custom SITE_URL wins, else <worker>.<subdomain>.workers.dev
    if (!env.SITE_URL) {
      const sub = await cf(`${acc}/workers/subdomain`).catch(() => null);
      if (sub?.subdomain) remember('SITE_URL', `https://${cfg.name}.${sub.subdomain}.workers.dev`);
    }
    if (process.env.SITE_URL) remember('SITE_URL', process.env.SITE_URL);
    if (env.SITE_URL) editWrangler((t) => t.replace(/("SITE_URL":\s*")[^"]*(")/, `$1${env.SITE_URL}$2`));

    ok(
      'cloudflare',
      `D1 ${d1.database_name} (${dbId}), queue ${queueName}, SITE_URL ${env.SITE_URL ?? 'unknown: open Workers & Pages in the dashboard once to create a workers.dev subdomain'}`
    );
  } catch (err) {
    const hint =
      err.status === 403 || err.status === 401
        ? ' (token needs: Workers Scripts, D1, Queues edit + Account Settings read)'
        : '';
    fail('cloudflare', String(err.message) + hint);
  }
}

// ---------------------------------------------------------------- stripe
async function stripe(path, params) {
  const body = params ? new URLSearchParams(flatten(params)) : undefined;
  const res = await fetch(`https://api.stripe.com/v1${path}`, {
    method: params ? 'POST' : 'GET',
    headers: { authorization: `Bearer ${env.STRIPE_SECRET_KEY}` },
    body,
  });
  const data = await res.json();
  if (data.error) throw new Error(`Stripe: ${data.error.message}`);
  return data;
}
function flatten(obj, prefix = '', out = {}) {
  for (const [k, v] of Object.entries(obj)) {
    if (v == null) continue;
    const key = prefix ? `${prefix}[${k}]` : k;
    if (typeof v === 'object') flatten(v, key, out);
    else out[key] = String(v);
  }
  return out;
}

async function stepStripe() {
  if (!env.STRIPE_SECRET_KEY) return skip('stripe', 'optional: set STRIPE_SECRET_KEY to enable payments');
  try {
    const { currency, plans } = JSON.parse(readFileSync(p('src/data/plans.json'), 'utf8'));
    let created = 0;
    for (const plan of plans) {
      const keys = plan.prices.map((x) => x.lookup_key);
      const qs = keys.map((k) => `lookup_keys[]=${encodeURIComponent(k)}`).join('&');
      const existing = (await stripe(`/prices?${qs}&limit=100`)).data;
      let productId = existing[0]?.product;
      for (const price of plan.prices) {
        if (existing.some((e) => e.lookup_key === price.lookup_key)) continue;
        productId ??= (
          await stripe('/products', { name: plan.name, description: plan.description, metadata: { plan_id: plan.id } })
        ).id;
        await stripe('/prices', {
          product: productId,
          currency,
          unit_amount: price.amount,
          lookup_key: price.lookup_key,
          recurring: price.interval ? { interval: price.interval } : undefined,
        });
        created++;
      }
    }

    let webhookMsg = 'webhook skipped (SITE_URL unknown or localhost)';
    if (env.SITE_URL && !env.SITE_URL.includes('localhost')) {
      const url = `${env.SITE_URL.replace(/\/$/, '')}/api/stripe/webhook`;
      const endpoints = (await stripe('/webhook_endpoints?limit=100')).data.filter((e) => e.url === url);
      if (endpoints.length && env.STRIPE_WEBHOOK_SECRET) {
        webhookMsg = 'webhook exists';
      } else {
        // The signing secret is only returned on creation, so recreate if we lost it.
        for (const e of endpoints)
          await fetch(`https://api.stripe.com/v1/webhook_endpoints/${e.id}`, {
            method: 'DELETE',
            headers: { authorization: `Bearer ${env.STRIPE_SECRET_KEY}` },
          });
        const wh = await stripe('/webhook_endpoints', { url, enabled_events: WEBHOOK_EVENTS });
        remember('STRIPE_WEBHOOK_SECRET', wh.secret);
        webhookMsg = `webhook created → ${url}`;
      }
    }
    ok(
      'stripe',
      `${created} price(s) created, ${webhookMsg}${env.STRIPE_SECRET_KEY.startsWith('sk_test') ? ' [TEST MODE]' : ' [LIVE MODE]'}`
    );
  } catch (err) {
    fail('stripe', err.message);
  }
}

// ---------------------------------------------------------------- deploy
function stepDeploy() {
  if (!env.CLOUDFLARE_API_TOKEN) return skip('deploy', 'set CLOUDFLARE_API_TOKEN');
  if (wranglerConfig().d1_databases[0].database_id === PLACEHOLDER_DB_ID)
    return skip('deploy', 'run the cloudflare step first');
  const secretsFile = '.secrets.deploy.env';
  write(
    secretsFile,
    WORKER_SECRETS.filter((k) => env[k])
      .map((k) => `${k}=${env[k]}`)
      .join('\n') + '\n'
  );
  const childEnv = {
    ...process.env,
    CLOUDFLARE_API_TOKEN: env.CLOUDFLARE_API_TOKEN,
    CLOUDFLARE_ACCOUNT_ID: env.CLOUDFLARE_ACCOUNT_ID,
  };
  try {
    sh('npm run build', { env: childEnv });
    sh('npx wrangler d1 migrations apply DB --remote', { env: childEnv });
    sh(`npx wrangler deploy --secrets-file ${secretsFile}`, { env: childEnv });
    ok('deploy', `live at ${env.SITE_URL ?? 'your workers.dev URL'} (admin: /admin)`);
  } catch {
    fail('deploy', 'see wrangler output above');
  } finally {
    unlinkSync(p(secretsFile));
  }
}

// ---------------------------------------------------------------- github
async function stepGithub() {
  const repo = env.GITHUB_REPO ?? gitRepoSlug();
  if (!repo) return skip('github', 'no GitHub remote: set GITHUB_REPO=owner/name');
  if (!env.CLOUDFLARE_API_TOKEN || !env.CLOUDFLARE_ACCOUNT_ID)
    return skip('github', 'needs Cloudflare token + account id');
  const secrets = { CLOUDFLARE_API_TOKEN: env.CLOUDFLARE_API_TOKEN, CLOUDFLARE_ACCOUNT_ID: env.CLOUDFLARE_ACCOUNT_ID };
  try {
    if (!env.GITHUB_TOKEN && has('gh')) {
      for (const [k, v] of Object.entries(secrets)) {
        const r = spawnSync('gh', ['secret', 'set', k, '--repo', repo], { input: v });
        if (r.status !== 0) throw new Error(`gh secret set ${k} failed: ${r.stderr}`);
      }
    } else if (env.GITHUB_TOKEN) {
      const gh = async (path, init = {}) => {
        const res = await fetch(`https://api.github.com/repos/${repo}${path}`, {
          ...init,
          headers: {
            authorization: `Bearer ${env.GITHUB_TOKEN}`,
            accept: 'application/vnd.github+json',
            'x-github-api-version': '2022-11-28',
          },
        });
        if (!res.ok) throw new Error(`GitHub ${res.status}: ${await res.text()}`);
        return res.status === 204 ? null : res.json().catch(() => null);
      };
      const { default: sodium } = await import('libsodium-wrappers');
      await sodium.ready;
      const { key, key_id } = await gh('/actions/secrets/public-key');
      for (const [k, v] of Object.entries(secrets)) {
        const sealed = sodium.crypto_box_seal(
          sodium.from_string(v),
          sodium.from_base64(key, sodium.base64_variants.ORIGINAL)
        );
        await gh(`/actions/secrets/${k}`, {
          method: 'PUT',
          body: JSON.stringify({ encrypted_value: sodium.to_base64(sealed, sodium.base64_variants.ORIGINAL), key_id }),
        });
      }
    } else {
      return skip('github', 'set GITHUB_TOKEN (fine-grained, Secrets: read/write) or install+login `gh`');
    }
    ok('github', `Actions secrets set on ${repo}; pushes to main now deploy`);
  } catch (err) {
    fail('github', err.message);
  }
}

// ---------------------------------------------------------------- run
const runners = {
  project: stepProject,
  local: stepLocal,
  cloudflare: stepCloudflare,
  stripe: stepStripe,
  deploy: stepDeploy,
  github: stepGithub,
};
for (const step of ALL_STEPS.filter((s) => steps.includes(s))) await runners[step]();

const failed = results.filter((r) => r[0] === '✖').length;
console.log(
  `\nsetup: ${results.filter((r) => r[0] === '✔').length} ok, ${results.filter((r) => r[0] === '…').length} skipped, ${failed} failed. Run \`npm run status\` for the full picture.`
);
process.exit(failed ? 1 : 0);
